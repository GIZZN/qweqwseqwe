export const DEFAULT_PROMPT = PROMPT_PRESETS[0].prompt;

export function getSystemPrompt(): string {
  if (typeof window === 'undefined') return DEFAULT_PROMPT;
  return localStorage.getItem('system_prompt') || DEFAULT_PROMPT;
}

export function saveSystemPrompt(prompt: string): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem('system_prompt', prompt);
}
